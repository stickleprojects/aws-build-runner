#!/usr/bin/env python3
"""Write IMAGE.md, the plain-English contract of the runner image, from manifest.json (which the bake
instance reports about itself, so it says what is actually installed).

  make-image-md.py [manifest.json] [IMAGE.md]
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Which jobs run on which instance type (part2-runner/PLAN.md). nproc is what jobs see.
INSTANCE_TYPES = [
    ("`check` (CI), `Check after review`", "c7i.xlarge", 4, "8 GB",
     "c6i.xlarge / m7i.xlarge spot, then c7i.xlarge on-demand. Never 2 vCPU or t3"),
    ("Claude jobs (review, mention, spec, descopes, PR title, evals)", "c7i.large", 2, "4 GB",
     "c7i-flex.large / t3.large"),
]


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "manifest.json"
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "IMAGE.md"
    m = json.loads(src.read_text())
    t, r = m["tools"], m["runner"]
    out = []
    w = out.append
    w("# The runner image: what it comes with")
    w("")
    w("Generated by `make-image-md.py` from `manifest.json`, which the bake instance reports about itself. "
      "Don't edit by hand. On every instance: `/etc/build-runner/manifest.json` (this) and "
      "`/etc/build-runner/instance.json` (that instance's type, `nproc`, memory).")
    w("")
    w(f"Built **{m['built']}** from {m['os']} (`{m['base_ami']}`), with versions pinned by spellbound3d "
      f"`{m['spellbound3d_commit'][:12]}`.")
    w("")
    w("## Tools (all on the PATH)")
    w("")
    w("| Tool | Version | Where it comes from |")
    w("|---|---|---|")
    rows = [
        ("Godot", t["godot"], "`tools/godot/version.env`, installed by spellbound3d's `scripts/install-godot.sh`; `godot` → `~/.local/opt/godot-<ver>/godot`"),
        ("Claude Code", t["claude_code"], "`CLAUDE_CODE_VERSION` in `.sdlc/scripts/install-claude.sh`; global, and in ghrunner's npm cache"),
        ("uv", t["uv"], "`UV_VERSION` in `.github/actions/setup-stack/action.yml`; global, and the wheel in ghrunner's pip cache"),
        ("gitleaks", t["gitleaks"], "spellbound3d's `scripts/install-gitleaks.sh`"),
        ("Python tools", "from `uv.lock`", "`uv sync --frozen` at bake time warms ghrunner's uv cache"),
        ("GitHub Actions runner", r["version"], "latest release at bake time, SHA-256 checked"),
        ("Node / npm", f"{t['node']} / {t['npm']}", "Ubuntu packages"),
        ("Python", t["python"], "Ubuntu packages (with venv, pip)"),
        ("git, jq, make", f"{t['git']}, {t['jq']}", "Ubuntu packages; also curl, unzip, zip, build-essential, libfontconfig1"),
    ]
    for name, version, source in rows:
        w(f"| {name} | {version} | {source} |")
    w("")
    w("## How jobs run")
    w("")
    w(f"- As **`{r['user']}`** (not root), in `{r['dir']}`, `HOME={r['home']}`, "
      "`NPM_CONFIG_PREFIX=$HOME/.local`; the same layout as the local runner.")
    w("- **One job per instance**: a just-in-time runner registration, then the instance powers off and is deleted "
      "(2-hour hard limit). Every job starts on a clean machine.")
    w("- The local runner's `job-started.sh` hook and allowlists run first: same repos, same actors, no forks.")
    w("- systemd: `NoNewPrivileges`, `ProtectSystem=full` (`/usr`, `/boot`, `/etc` read-only), private `/tmp`.")
    w("")
    w("## Not included, on purpose")
    w("")
    for item in m["not_included"]:
        w(f"- {item}")
    w("")
    w("## Instance types per job")
    w("")
    w("| Jobs | Instance | vCPU (`nproc`) | Memory | Fallback when spot is short |")
    w("|---|---|---|---|---|")
    for jobs, itype, cpus, mem, fallback in INSTANCE_TYPES:
        w(f"| {jobs} | {itype} | {cpus} | {mem} | {fallback} |")
    w("")
    w("Changes to the image arrive as PRs in this repo that update this file, so the diff shows what moved.")
    w("")
    dst.write_text("\n".join(out))
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
